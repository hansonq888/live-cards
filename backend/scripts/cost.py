"""What one full match costs in model calls: every moment a live viewer would get an AI line
for, through the real agents (Explainer, Verifier, Reviewer, rewrites), plus the four-profile
Personalizer fan-out on goals and rating upgrades, exactly as a live session does it.

Jobs are built while the match replays (so each one sees the engine as it was at that moment),
then explained with a few in flight at once. Tokens are what the model API reports; dollars use
the list prices in livecards/agents/meter.py. Writes docs/cost.md and docs/cost.json.

    uv run --extra agents python scripts/cost.py
"""

from __future__ import annotations

import asyncio
import json
import time
from pathlib import Path

from livecards.agents import meter
from livecards.agents.explainer import job_for
from livecards.agents.personalizer import SHOWCASE, PersonalizeRequest, personalize
from livecards.agents.pipeline import explain
from livecards.engine.engine import MatchEngine
from livecards.replay import feed, ticks
from livecards.server.session import (
    MODEL_MOMENTS,
    SHOWCASE_MOMENTS,
    explainer_agent,
    load_match,
    personalizer_agent,
    reviewer_agent,
)

ROOT = Path(__file__).resolve().parents[2]


async def main() -> None:
    match = load_match(7)
    roster = {n for p in match.meta.players for n in (p.name, p.short)}
    engine = MatchEngine(match.meta)
    jobs = []
    for tick in ticks(match):
        for m in feed(engine, match, tick):
            if m.type in MODEL_MOMENTS and m.importance >= 0.3:
                jobs.append(job_for(m, engine))
    ledger = meter.Ledger()
    meter.current.set(ledger)
    sem = asyncio.Semaphore(4)
    aired = rewrites = templates = 0
    t0 = time.perf_counter()

    async def one(job) -> None:
        nonlocal aired, rewrites, templates
        async with sem:
            r = await explain(job, explainer_agent(), roster, lambda _e: None, reviewer_agent())
        if r is None or r.source != "model":
            templates += 1
            return
        aired += 1
        rewrites += r.attempts > 1
        if job.moment.type in SHOWCASE_MOMENTS and job.moment.importance >= 0.55:
            req = PersonalizeRequest(job, r.text, match.meta.home.name, match.meta.away.name)
            async with sem:
                await personalize(req, [p for p in SHOWCASE if p.key != "casual.en.neutral"],
                                  personalizer_agent(), roster, lambda _e: None, reviewer_agent())

    await asyncio.gather(*(one(j) for j in jobs))
    s = ledger.summary()
    res = {"moments_explained": len(jobs), "ai_lines_aired": aired, "fell_back_to_stats_line": templates,
           "fixed_by_rewrite": rewrites, "wall_s": round(time.perf_counter() - t0), **s}
    (ROOT / "docs" / "cost.json").write_text(json.dumps(res, indent=2))
    rows = "\n".join(f"| {k} | {v['model']} | {v['calls']} | {v['tokens']:,} | ${v['usd']:.4f} |"
                     for k, v in s["by_agent"].items())
    (ROOT / "docs" / "cost.md").write_text(f"""# What a match costs

One full 90-minute match through the real agents on Microsoft Foundry: every moment a live viewer
gets an AI line for ({len(jobs)} moments), each through the Explainer, the code Verifier and the
Reviewer (with rewrites when a check fails), plus the Personalizer's three extra fan profiles on
goals and rating upgrades. Generated by `backend/scripts/cost.py`.

| | |
|---|---|
| **Estimated cost per match** | **${s['usd']:.2f}** ({s['prices']}) |
| Model calls | {s['calls']} |
| Tokens | {s['tokens']:,} |
| AI lines aired / fell back to the stats line | {aired} / {templates} |
| Fixed by a rewrite after a failed check | {rewrites} |

| Agent | Model | Calls | Tokens | Cost |
|---|---|---|---|---|
{rows}

This is the cost of producing the lines once. Verified lines and translations are cached per
match, so every further viewer of the same match reuses them instead of calling a model again.
Tokens are as reported by the model API; dollars are estimates from list prices.
""")
    print(json.dumps({k: v for k, v in res.items() if k != "by_agent"}, indent=2))


if __name__ == "__main__":
    asyncio.run(main())
