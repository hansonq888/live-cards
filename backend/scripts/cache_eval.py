"""How much the verified-line cache saves: several viewers watch the same stretch of the match,
one after another, through real live sessions with the AI on. The first viewer's lines are
generated and checked; later viewers reuse the verified lines and translations instead of
calling a model. Each viewer's model calls come from its own token ledger.

    uv run --extra agents python scripts/cache_eval.py
Writes docs/cache.md and docs/cache.json.
"""

from __future__ import annotations

import asyncio
import json
from pathlib import Path

from livecards.server import session as S

ROOT = Path(__file__).resolve().parents[2]
START, SPEED, WALL_S, VIEWERS = 3600.0, 6.0, 150.0, 3  # 60' to 75', the hero goal at 65'


async def viewer() -> dict:
    async def send(_m):
        return None
    s = S.LiveSession(send, speed=SPEED, start=START)
    run = asyncio.create_task(s.run())
    await asyncio.sleep(WALL_S)
    run.cancel()
    while s.tasks:  # let explanations already under way finish, so every call is counted
        await asyncio.gather(*list(s.tasks), return_exceptions=True)
    return {"lines_aired": s.metrics["model_lines"], **s.ledger.summary()}


async def main() -> None:
    rows = []
    for i in range(VIEWERS):
        r = await viewer()
        rows.append(r)
        print(f"viewer {i + 1}: {r['calls']} model calls, {r['cache_hits']} reused, ${r['usd']:.4f}")
    first, later = rows[0], rows[1:]
    later_calls = sum(r["calls"] for r in later) / len(later)
    saved = round(100 * (1 - later_calls / first["calls"])) if first["calls"] else 0
    res = {"window": "60'-75' at 6x", "viewers": rows, "first_viewer_calls": first["calls"],
           "later_viewer_calls_avg": later_calls, "calls_saved_pct": saved}
    (ROOT / "docs" / "cache.json").write_text(json.dumps(res, indent=2))
    lines = "\n".join(f"| {i + 1} | {r['calls']} | {r['cache_hits']} | {r['tokens']:,} | ${r['usd']:.4f} |"
                      for i, r in enumerate(rows))
    (ROOT / "docs" / "cache.md").write_text(f"""# What the cache saves

{VIEWERS} viewers watch the same 15 minutes of the match (60' to 75', including the 65' goal), one
after another, through real live sessions with the AI on (Microsoft Foundry). The first viewer
gets every line generated and checked; the rest reuse the verified lines and translations.
Generated by `backend/scripts/cache_eval.py`.

| Viewer | Model calls | Reused from cache | Tokens | Cost (est.) |
|---|---|---|---|---|
{lines}

**Each later viewer made {saved}% fewer model calls than the first** ({later_calls:.0f} vs
{first['calls']}). Calls that remain for later viewers are moments the first viewer never got an
AI line for (busy stretches where the in-flight limit was reached, or a line that fell back to the
stats line), which later viewers try again.
""")
    print(json.dumps({k: v for k, v in res.items() if k != "viewers"}, indent=2))


if __name__ == "__main__":
    asyncio.run(main())
